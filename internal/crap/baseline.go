package crap

import (
	"bufio"
	"cmp"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

// tolerance absorbs rounding: the baseline stores one decimal.
const tolerance = 0.05

// Baseline maps a function key to the CRAP it was allowed to have when recorded.
type Baseline map[string]float64

// Report compares the current scores against the baseline.
type Report struct {
	New      []string // above the maximum and not in the baseline
	Worse    []string // in the baseline, but scoring higher than recorded
	Improved []string // in the baseline, now at or below the maximum
}

func (r Report) Failed() bool { return len(r.New) > 0 || len(r.Worse) > 0 }

func Check(funcs []Func, base Baseline, max float64) Report {
	var r Report
	for _, f := range funcs {
		score := f.Score()
		allowed, known := base[f.Key]
		switch {
		case known && score > allowed+tolerance:
			r.Worse = append(r.Worse, fmt.Sprintf("%s: CRAP %.1f (baseline %.1f, complexity %d, coverage %.1f%%)",
				f.Key, score, allowed, f.Complexity, f.Coverage*100))
		case known && score <= max:
			r.Improved = append(r.Improved, fmt.Sprintf("%s no longer exceeds CRAP %g", f.Key, max))
		case !known && score > max:
			r.New = append(r.New, fmt.Sprintf("%s: CRAP %.1f > %g (complexity %d, coverage %.1f%%)",
				f.Key, score, max, f.Complexity, f.Coverage*100))
		}
	}
	return r
}

// Ratchet returns the baseline with improvements recorded: entries that dropped to the maximum
// or below are removed and lower scores replace higher ones. It refuses (Report.Failed) to add a
// function or to raise a score, so updating the baseline can never hide a regression.
func Ratchet(funcs []Func, base Baseline, max float64) (Baseline, Report) {
	r := Check(funcs, base, max)
	if r.Failed() {
		return base, r
	}
	next := Baseline{}
	for _, f := range funcs {
		if score := f.Score(); score > max {
			next[f.Key] = round(score)
		}
	}
	return next, r
}

// Init records every function above the maximum. Only for adopting goquality in a module:
// it refuses when a baseline already exists.
func Init(funcs []Func, max float64) Baseline {
	base := Baseline{}
	for _, f := range funcs {
		if score := f.Score(); score > max {
			base[f.Key] = round(score)
		}
	}
	return base
}

func round(score float64) float64 {
	v, _ := strconv.ParseFloat(strconv.FormatFloat(score, 'f', 1, 64), 64)
	return v
}

// ReadBaseline reads "<crap> <file>:<function>" lines; '#' starts a comment.
func ReadBaseline(path string) (Baseline, bool, error) {
	f, err := os.Open(path)
	if errors.Is(err, os.ErrNotExist) {
		return Baseline{}, false, nil
	}
	if err != nil {
		return nil, false, err
	}
	defer f.Close()
	base := Baseline{}
	scanner := bufio.NewScanner(f)
	for line := 1; scanner.Scan(); line++ {
		text := strings.TrimSpace(scanner.Text())
		if text == "" || strings.HasPrefix(text, "#") {
			continue
		}
		fields := strings.Fields(text)
		score, err := strconv.ParseFloat(fields[0], 64)
		if len(fields) != 2 || err != nil {
			return nil, true, fmt.Errorf("%s:%d: want \"<crap> <file>:<function>\"", path, line)
		}
		base[fields[1]] = score
	}
	return base, true, scanner.Err()
}

func WriteBaseline(path string, base Baseline, max float64) error {
	keys := make([]string, 0, len(base))
	for k := range base {
		keys = append(keys, k)
	}
	slices.SortFunc(keys, func(a, b string) int { // worst first, ties by name
		if c := cmp.Compare(base[b], base[a]); c != 0 {
			return c
		}
		return strings.Compare(a, b)
	})
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by goquality. Pre-existing functions with CRAP > %g.\n", max)
	b.WriteString("# Format: <crap> <file>:<function>. This file only shrinks: goquality refuses to add or raise entries.\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "%.1f %s\n", base[k], k)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(b.String()), 0o600)
}
